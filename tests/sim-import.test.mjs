import { chromium } from 'playwright';
const BASE = process.env.BASE_URL; // the app, served by tests/run.mjs
const ZIP = process.env.SIM_ZIP; // synthetic backup from tests/fixtures/sim-backup.mjs
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await b.newContext({ viewport: { width: 1200, height: 900 }, timezoneId: 'Asia/Karachi' });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
const ok = (c, msg) => { console.log((c ? 'PASS ' : 'FAIL ') + msg); if (!c) process.exitCode = 1; };
const local = async () => { await p.waitForTimeout(400); return p.evaluate(() => JSON.parse(localStorage.getItem('ck-tracker') || '{}')); };
await p.goto(BASE);
// existing data: NBME 11 already logged with a different score, IM Form 3 hidden
await p.evaluate(() => localStorage.setItem('ck-tracker', JSON.stringify({ v: 2, items: { 'nbme-11': { status: 2, score: '244', pct: '', date: '2026-08-20', notes: 'my notes' } }, removed: ['cms-med-3'] })));
await p.reload();
await p.click('#tab-nbme');
await p.setInputFiles('#sim-import', ZIP);
await p.waitForSelector('.sim-list');
const txt = await p.textContent('.sim-list');
ok(txt.includes('Assessments & CMS forms (5)') && txt.includes('Custom question sets (1)') && txt.includes('Not imported (1)'), 'sections: 5 forms, 1 custom set, 1 skipped');
ok(txt.includes('NBME 6') && txt.includes('163/184') && txt.includes('245'), 'NBME 6 row shows 163/184 and 245');
ok(txt.includes('UWSA 3') && txt.includes('91/160') && txt.includes('211'), 'UWSA 3 row');
ok(/score: yours 244, simulator 238/.test(txt), 'conflict on NBME 11 flagged');
ok(txt.includes('Unhides this form'), 'hidden IM Form 3 will be unhidden');
ok(/In progress|Not finished/.test(txt), 'unfinished form skipped');
await p.click('.sheet .actions .btn.primary');
await p.waitForTimeout(500);
let s = await local();
const it = s.items;
ok(it['nbme-6'].status === 1 && it['nbme-6'].score === '245' && it['nbme-6'].pct === '88.6' && it['nbme-6'].date === '2026-09-27', 'NBME 6 imported: ' + JSON.stringify(it['nbme-6']));
ok(it['nbme-11'].score === '244' && it['nbme-11'].status === 2 && it['nbme-11'].pct === '72' && it['nbme-11'].notes === 'my notes', 'NBME 11: kept score/status/notes, filled %');
ok(it['uwsa-3'].score === '211' && it['uwsa-3'].pct === '56.9', 'UWSA 3 imported');
ok(it['cms-med-3'].score === '84' && it['cms-fm-1'].score === '82', 'CMS imported as % correct');
ok(!it['cms-med-1'], 'unfinished not imported');
ok(!s.removed.includes('cms-med-3'), 'IM Form 3 unhidden');
ok(s.log.length === 1 && s.log[0].src === 'Other' && s.log[0].note.startsWith('Exam Simulator'), 'custom set → qbank session');
ok((await p.textContent('#toasts')).includes('Imported 5 forms and 1 qbank session'), 'toast: ' + await p.textContent('#toasts'));
await p.setInputFiles('#sim-import', ZIP);
await p.waitForSelector('.sim-list');
ok((await p.textContent('.sheet .actions .btn.primary')) === 'Nothing new to import', 're-import is a no-op');
await p.click('text=Replace my values where they differ');
ok((await p.textContent('.sheet .actions .btn.primary')) === 'Import 1 change', 'overwrite offers the 1 conflict');
await p.click('.sheet .actions .btn.primary'); await p.waitForTimeout(400);
ok((await local()).items['nbme-11'].score === '238', 'overwrite applied');
await p.click('#toasts button'); await p.waitForTimeout(400);
ok((await local()).items['nbme-11'].score === '244', 'undo restores');
await p.setInputFiles('#import', ZIP);
await p.waitForSelector('.sim-list');
ok(true, 'zip via Import backup opens simulator preview');
await p.keyboard.press('Escape');
await p.setViewportSize({ width: 375, height: 800 });
await p.click('#tab-nbme'); await p.setInputFiles('#sim-import', ZIP); await p.waitForSelector('.sim-list');
ok(await p.evaluate(() => document.documentElement.scrollWidth) <= 375, 'no horizontal scroll on phone');
ok(errs.length === 0, 'no errors ' + JSON.stringify(errs));
await b.close();
